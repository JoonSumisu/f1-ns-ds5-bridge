// 单 HID 接口, IN 0x81 + OUT 0x01 双端点 (同真 DS5 有线), 1ms 轮询
#define DS5_CFG_DESC_LEN (9 + 9 + 9 + 7 + 7)

const uint8_t ds5_configuration_descriptor[] = {
    // Config: 1 接口, 总长, 总线供电(bit7 规范要求置 1), 500mA
    0x09, TUSB_DESC_CONFIGURATION, U16_TO_U8S_LE(DS5_CFG_DESC_LEN), 0x01, 0x01, 0x00,
    0x80  /* bus powered + reserved bit */, 250,

    // Interface #0: HID, 无备用, 无协议, iInterface=0 (不能指向不存在的字符串)
    0x09, TUSB_DESC_INTERFACE, 0x00, 0x00, 0x02, TUSB_CLASS_HID, 0x00, 0x00, 0x00,

    // HID 描述符: 报告描述符长度
    0x09, HID_DESC_TYPE_HID, U16_TO_U8S_LE(0x0111), 0x00, 0x01, HID_DESC_TYPE_REPORT,
    U16_TO_U8S_LE(sizeof(ds5_hid_report_descriptor)),

    // EP OUT 0x01, 64B, 1ms
    0x07, TUSB_DESC_ENDPOINT, 0x01, TUSB_XFER_INTERRUPT, U16_TO_U8S_LE(64), 1,

    // EP IN 0x81, 64B, 1ms
    0x07, TUSB_DESC_ENDPOINT, 0x81, TUSB_XFER_INTERRUPT, U16_TO_U8S_LE(64), 1,
};

// 字符串: [0]=语言, 1=厂商, 2=产品, 3=序列号
